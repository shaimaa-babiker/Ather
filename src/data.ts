// ── يبني مجموعة أساسية: يفضل بيانات JSON على البيانات الثابتة
function buildCoreSet(id: string): ASet {
  const meta = CORE_META.find(m => m.id === id)!;
  if (AZ?.sets?.[id]?.length) {
    return { ...meta, items: AZ.sets[id] as Dhikr[] };
  }
  return ADHKAR_STATIC.find(s => s.id === id)!;
}

// ── المجموعات الأساسية الخمس
export const ADHKAR: ASet[] = CORE_META.map(m => buildCoreSet(m.id));
export const getSet = (id: string): ASet | undefined => {
  // ابحث أولاً في الأساسية
  const core = ADHKAR.find(s => s.id === id);
  if (core) return core;
  // ثم في جميع الفئات من azkar.json
  return ALL_ADHKAR.find(s => s.id === id);
};

// ── جميع فئات حصن المسلم (بعد تشغيل fetch:azkar)
export const ALL_ADHKAR: ASet[] = (() => {
  if (!AZ?.categories?.length) return ADHKAR;
  return (AZ.categories as any[]).map((cat: any) => {
    const id    = String(cat.id);
    const title = String(cat.title || '');
    // إذا كانت فئة أساسية نستخدمها كما هي
    if (CORE_IDS.has(id)) return buildCoreSet(id);
    return {
      id,
      title,
      tag:   title,
      desc:  'حصن المسلم — الأذكار المأثورة',
      icon:  iconForTitle(title),
      min:   Math.max(1, Math.round((cat.items as any[]).reduce((s: number, x: any) => s + (Number(x.count) || 1), 0) / 60)),
      items: (cat.items as any[]) as Dhikr[],
    } as ASet;
  });
})();

